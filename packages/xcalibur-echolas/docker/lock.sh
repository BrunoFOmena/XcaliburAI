#!/usr/bin/env bash
# Regenerate the explicit linux-64 locks from the environment files (needs micromamba).
#   docker/lock.sh            (run from packages/xcalibur-echolas)
set -euo pipefail

envs=src/xcalibur_echolas/workflow/envs
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
for name in echolas echolas-pca; do
    micromamba create -y -q -r "$tmp/root" -p "$tmp/$name" -f "$envs/$name.yml"
    {
        echo "# Generated by docker/lock.sh from $name.yml; do not edit."
        micromamba env export -r "$tmp/root" -p "$tmp/$name" --explicit --md5 \
            | grep -v '^#'
    } > "$envs/$name.linux-64.lock"
    echo "wrote $envs/$name.linux-64.lock"
done
